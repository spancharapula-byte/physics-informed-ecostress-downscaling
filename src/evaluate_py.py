# ============================================================
# Configuration
# ============================================================

BATCH_SIZE = 2

TRAIN_RATIO = 0.70

VALIDATION_RATIO = 0.15

RANDOM_SEED = 42


# ============================================================
# Device
# ============================================================

DEVICE = torch.device(
    "cuda"
    if torch.cuda.is_available()
    else "cpu"
)


# ============================================================
# Load processed data
# ============================================================

def load_processed_data():
    """
    Load the existing validation dataset created by preprocessing.
    """

    if not VAL_DATA_PATH.exists():
        raise FileNotFoundError(
            f"Validation dataset not found:\n{VAL_DATA_PATH}"
        )

    data = torch.load(
        VAL_DATA_PATH,
        map_location="cpu",
        weights_only=True
    )

    X = data["inputs"].cpu().numpy()
    Y = data["targets"].cpu().numpy()

    valid_mask = np.isfinite(Y)

    print("Inputs loaded:", X.shape)
    print("Targets loaded:", Y.shape)

    return X, Y, valid_mask


# ============================================================
# Recreate the same test split used by dataset.py
# ============================================================

def get_test_data(
    X,
    Y,
    valid_mask
):
    """
    Reproduce the deterministic train/validation/test
    split used by dataset.py.
    """

    total_samples = len(X)

    rng = np.random.default_rng(
        RANDOM_SEED
    )

    indices = rng.permutation(
        total_samples
    )


    # --------------------------------------------------------
    # Calculate split sizes
    # --------------------------------------------------------

    train_size = int(
        total_samples * TRAIN_RATIO
    )

    validation_size = int(
        total_samples * VALIDATION_RATIO
    )


    # --------------------------------------------------------
    # Get test indices
    # --------------------------------------------------------

    test_indices = indices[
        train_size + validation_size:
    ]


    # --------------------------------------------------------
    # Extract test data
    # --------------------------------------------------------

    X_test = X[
        test_indices
    ]

    Y_test = Y[
        test_indices
    ]

    valid_mask_test = valid_mask[
        test_indices
    ]


    return (
        X_test,
        Y_test,
        valid_mask_test
    )


# ============================================================
# Calculate metrics
# ============================================================

def calculate_metrics(
    predictions,
    targets,
    valid_mask
):
    """
    Calculate RMSE, MAE, and R² using only valid pixels.

    Parameters
    ----------
    predictions : numpy.ndarray
        Predicted LST values.

    targets : numpy.ndarray
        Reference LST values.

    valid_mask : numpy.ndarray
        Boolean mask indicating valid target pixels.
    """

    predictions = predictions.astype(
        np.float64
    )

    targets = targets.astype(
        np.float64
    )

    valid_mask = valid_mask.astype(
        bool
    )


    # --------------------------------------------------------
    # Make sure mask shape matches target
    # --------------------------------------------------------

    if valid_mask.shape != targets.shape:

        raise ValueError(
            "Valid mask shape does not match "
            "target shape."
        )


    # --------------------------------------------------------
    # Select valid pixels only
    # --------------------------------------------------------

    valid_predictions = predictions[
        valid_mask
    ]

    valid_targets = targets[
        valid_mask
    ]


    if len(valid_targets) == 0:

        raise ValueError(
            "No valid pixels were found "
            "for evaluation."
        )


    # --------------------------------------------------------
    # Mean Squared Error
    # --------------------------------------------------------

    mse = np.mean(
        (
            valid_predictions
            -
            valid_targets
        ) ** 2
    )


    # --------------------------------------------------------
    # Root Mean Squared Error
    # --------------------------------------------------------

    rmse = np.sqrt(
        mse
    )


    # --------------------------------------------------------
    # Mean Absolute Error
    # --------------------------------------------------------

    mae = np.mean(
        np.abs(
            valid_predictions
            -
            valid_targets
        )
    )


    # --------------------------------------------------------
    # R²
    # --------------------------------------------------------

    ss_res = np.sum(
        (
            valid_targets
            -
            valid_predictions
        ) ** 2
    )

    ss_tot = np.sum(
        (
            valid_targets
            -
            np.mean(valid_targets)
        ) ** 2
    )


    if ss_tot == 0:

        r2 = 0.0

    else:

        r2 = 1.0 - (
            ss_res / ss_tot
        )


    return (
        rmse,
        mae,
        r2
    )


# ============================================================
# Load trained model
# ============================================================

def load_model():
    """
    Load the best trained U-Net model.
    """

    model = UNet(
        in_channels=9,
        out_channels=1
    ).to(
        DEVICE
    )


    model_path = (
        MODEL_DIR
        /
        "best_unet_model.pth"
    )


    if not model_path.exists():

        raise FileNotFoundError(
            "Trained model not found:\n"
            f"{model_path}"
        )


    model.load_state_dict(
        torch.load(
            model_path,
            map_location=DEVICE,
            weights_only=True
        )
    )


    model.eval()


    return model


# ============================================================
# Generate test predictions
# ============================================================

def generate_predictions(
    model,
    X_test,
    batch_size=BATCH_SIZE
):
    """
    Generate predicted LST maps for the test inputs.
    """

    predictions = []


    with torch.no_grad():

        for start in range(
            0,
            len(X_test),
            batch_size
        ):

            end = min(
                start + batch_size,
                len(X_test)
            )


            # ------------------------------------------------
            # Convert test batch to tensor
            # ------------------------------------------------

            inputs = torch.tensor(
                X_test[start:end],
                dtype=torch.float32,
                device=DEVICE
            )

            inputs = (inputs - INPUT_MEANS.to(DEVICE)) / INPUT_STDS.to(DEVICE)

            # ------------------------------------------------
            # U-Net prediction
            # ------------------------------------------------

            outputs = model(
                inputs
            )
            outputs = (outputs * TARGET_STD + TARGET_MEAN)


            # ------------------------------------------------
            # Move prediction back to CPU
            # ------------------------------------------------

            predictions.append(
                outputs.cpu().numpy()
            )


    return np.concatenate(
        predictions,
        axis=0
    )


