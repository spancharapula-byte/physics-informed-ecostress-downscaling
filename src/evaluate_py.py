# Evaluate model
# ============================================================

def evaluate_model():
    """
    Run the complete test evaluation.
    """

    print(
        "Using device:",
        DEVICE
    )


    # --------------------------------------------------------
    # Load processed data
    # --------------------------------------------------------

    (
        X,
        Y,
        valid_mask
    ) = load_processed_data()


    # --------------------------------------------------------
    # Check shapes
    # --------------------------------------------------------

    if X.ndim != 4:

        raise ValueError(
            f"X must be 4D, got {X.ndim}D."
        )


    if Y.ndim != 4:

        raise ValueError(
            f"Y must be 4D, got {Y.ndim}D."
        )


    if X.shape[1] != 9:

        raise ValueError(
            "Expected 9 input channels."
        )


    if Y.shape[1] != 1:

        raise ValueError(
            "Expected one target LST channel."
        )


    if len(X) != len(Y):

        raise ValueError(
            "X and Y must contain the same "
            "number of samples."
        )


    # --------------------------------------------------------
    # Get test split
    # --------------------------------------------------------

    X_test = X
    Y_test = Y
    valid_mask_test = valid_mask

    print(
        "\nTest input shape:",
        X_test.shape
    )

    print(
        "Test target shape:",
        Y_test.shape
    )

    print(
        "Test mask shape:",
        valid_mask_test.shape
    )


    # --------------------------------------------------------
    # Load trained model
    # --------------------------------------------------------

    model = load_model()


    # --------------------------------------------------------
    # Generate predictions
    # --------------------------------------------------------

    predictions = generate_predictions(
        model,
        X_test
    )


    print(
        "Prediction shape:",
        predictions.shape
    )


    # --------------------------------------------------------
    # Calculate metrics
    # --------------------------------------------------------

    (
        rmse,
        mae,
        r2
    ) = calculate_metrics(
        predictions,
        Y_test,
        valid_mask_test
    )


    # --------------------------------------------------------
    # Print results
    # --------------------------------------------------------

    print(
        "\nTest Results"
    )

    print(
        "------------"
    )

    print(
        f"RMSE: {rmse:.4f}"
    )

    print(
        f"MAE:  {mae:.4f}"
    )

    print(
        f"R²:   {r2:.4f}"
    )


    # --------------------------------------------------------
    # Save predictions
    # --------------------------------------------------------

    prediction_path = (
        MODEL_DIR
        /
        "test_predictions.npy"
    )


    np.save(
        prediction_path,
        predictions
    )


    print(
        "\nPredictions saved to:"
    )

    print(
        prediction_path
    )


    # --------------------------------------------------------
    # Save test targets
    # --------------------------------------------------------

    target_path = (
        MODEL_DIR
        /
        "test_targets.npy"
    )


    np.save(
        target_path,
        Y_test
    )


    # --------------------------------------------------------
    # Save valid mask
    # --------------------------------------------------------

    mask_path = (
        MODEL_DIR
        /
        "test_valid_mask.npy"
    )


    np.save(
        mask_path,
        valid_mask_test
    )


    # --------------------------------------------------------
    # Save metrics
    # --------------------------------------------------------

    metrics = {
        "RMSE": rmse,
        "MAE": mae,
        "R2": r2
    }


    metrics_path = (
        MODEL_DIR
        /
        "evaluation_metrics.npy"
    )


    np.save(
        metrics_path,
        metrics,
        allow_pickle=True
    )


    print(
        "Metrics saved to:"
    )

    print(
        metrics_path
    )


    return (
        predictions,
        Y_test,
        valid_mask_test,
        metrics
    )


# ============================================================
